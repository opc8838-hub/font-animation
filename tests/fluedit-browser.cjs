// node tests/fluedit-browser.cjs <node_modules directory> <browser executable> [base URL] [output directory]
const path = require('node:path');
const { chromium } = require(path.resolve(process.argv[2] || 'node_modules', 'playwright'));
const fs = require('fs');
const assert = require('assert/strict');
const base = (process.argv[4] || 'http://127.0.0.1:8765').replace(/\/$/, '');
const output = path.resolve(process.argv[5] || path.join(__dirname, '../output/fluedit'));
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.argv[3] || undefined });
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, acceptDownloads: true });
  await context.addInitScript(() => {
    if (!sessionStorage.getItem('fluedit-test-started')) {
      localStorage.clear();
      localStorage.setItem('cellmotion-site-theme', 'dark');
      localStorage.setItem('cellmotion-site-language', 'zh');
      sessionStorage.setItem('fluedit-test-started', 'yes');
    }
  });
  const page = await context.newPage();
  const errors = [];
  context.on('page', current => current.on('pageerror', error => errors.push(error.message)));
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  const ready = () => page.waitForFunction(() => !!window.CellMotionFluedit, null, { timeout: 60000 });
  const select = async (id, value) => page.locator(`#${id}`).selectOption(value, { force: true });
  try {
  await page.goto(`${base}/fluedit/`, { waitUntil: 'domcontentloaded' });
  await ready();
  assert.equal(await page.locator('body').getAttribute('data-editor-theme'), 'dark');
  await page.screenshot({ path: `${output}/fluedit-cellmotion-dark.png` });
  console.log('Ready: dark three-column workspace');
  await page.locator('[data-shape="iris"]').click();
  await page.locator('[data-preset="2"]').click();
  await page.locator('[data-panel="motion"]').first().click();
  await page.locator('#motion-enabled').check();
  await page.locator('#motion-shift-enabled').check();
  await page.locator('#motion-spread-enabled').check();
  await page.waitForFunction(() => document.querySelectorAll('#cmTimeline .me-choreo-block').length === 3);
  const time1 = await page.evaluate(() => CellMotionFluedit.time());
  await page.waitForFunction(time => CellMotionFluedit.time() > time + .1, time1);
  await page.locator('#cmPlay').click();
  await page.locator('#cmScrubber').fill('1');
  assert.equal(Math.round(await page.evaluate(() => CellMotionFluedit.time())), 1);
  const beforeTheme = await page.evaluate(() => CellMotionFluedit.state());
  await page.locator('.site-theme-toggle').click();
  assert.deepEqual(await page.evaluate(() => CellMotionFluedit.state()), beforeTheme);
  await page.locator('.site-language-toggle').click();
  await page.waitForFunction(() => document.documentElement.dataset.siteLanguage === 'en');
  await page.waitForFunction(() => !document.documentElement.classList.contains('cm-language-fading'));
  assert.deepEqual(await page.evaluate(() => CellMotionFluedit.state()), beforeTheme);
  await page.screenshot({ path: `${output}/fluedit-cellmotion-light-en.png` });
  console.log('Verified shape, palette, three animation lanes, pause/seek, theme and language state preservation');
  await select('cmCanvasPreset', '1080x1920');
  let bounds = await page.locator('#stage').boundingBox();
  assert.ok(Math.abs(bounds.width / bounds.height - 9 / 16) < .002);
  await select('cmCanvasPreset', '1080x1080');
  bounds = await page.locator('#stage').boundingBox();
  assert.ok(Math.abs(bounds.width / bounds.height - 1) < .002);
  await select('cmCanvasPreset', 'custom');
  await page.locator('#cmWidth').fill('320'); await page.locator('#cmWidth').dispatchEvent('change');
  await page.locator('#cmHeight').fill('480'); await page.locator('#cmHeight').dispatchEvent('change');
  await page.locator('#cmBackground').fill('#c5dded');
  await page.locator('#cmBackground').dispatchEvent('input');
  await page.locator('.tc-export-shortcut').click();
  await select('cmDuration', 'custom');
  await page.locator('#cmSeconds').fill('1'); await page.locator('#cmSeconds').dispatchEvent('change');
  await select('cmFps', '15');
  const savedPromise = page.waitForEvent('download');
  await page.locator('#saveScheme').click();
  const saved = await savedPromise;
  await saved.saveAs(`${output}/fluedit-cellmotion-project.json`);
  const state = await page.evaluate(() => CellMotionFluedit.state());
  await page.locator('#restoreScheme').click();
  await page.locator('#schemeFile').setInputFiles(`${output}/fluedit-cellmotion-project.json`);
  await page.waitForFunction(() => CellMotionFluedit.state().shape === 'iris');
  assert.deepEqual(await page.evaluate(() => CellMotionFluedit.state()), state);
  assert.equal((await page.evaluate(() => CellMotionFluedit.settings())).height, 480);
  const imported = await page.evaluate(() => CellMotionFluedit.state());
  await page.locator('#schemeFile').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"type":"wrong","version":1}') });
  assert.deepEqual(await page.evaluate(() => CellMotionFluedit.state()), imported);
  await page.reload({ waitUntil: 'domcontentloaded' }); await ready();
  assert.deepEqual(await page.evaluate(() => CellMotionFluedit.state()), state);
  assert.equal((await page.evaluate(() => CellMotionFluedit.settings())).height, 480);
  console.log('Verified 9:16, 1:1, custom aspect, scheme download/import and refresh persistence');
  await page.locator('.tc-export-shortcut').click();
  await page.evaluate(() => CellMotionFluedit.seek(0));
  await page.locator('#stage').screenshot({ path: `${output}/fluedit-cellmotion-stage.png` });
  for (const [id, format] of [['export', 'png'], ['cmExportGif', 'gif'], ['cmExportMp4', 'mp4']]) {
    console.log(`Exporting ${format}`);
    const pending = page.waitForEvent('download', { timeout: 120000 });
    await page.locator(`#${id}`).click();
    const download = await pending;
    await download.saveAs(`${output}/fluedit-cellmotion-export.${format}`);
    assert.ok(fs.statSync(`${output}/fluedit-cellmotion-export.${format}`).size > 1000);
  }
  await select('cmCanvasPreset', '1080x1080');
  await select('cmExportScale', '0.25');
  const squarePending = page.waitForEvent('download');
  await page.locator('#export').click();
  await (await squarePending).saveAs(`${output}/fluedit-cellmotion-square.png`);
  await select('cmExportScale', '1');
  await page.locator('[data-panel="color"]').first().click();
  await page.locator('[data-tab="areas"]').click();
  await page.locator('#first-area').click();
  assert.equal((await page.evaluate(() => CellMotionFluedit.state())).areas.length, 1);
  await page.locator('#duplicate-area').click();
  assert.equal((await page.evaluate(() => CellMotionFluedit.state())).areas.length, 2);
  await page.locator('#remove').click();
  assert.equal((await page.evaluate(() => CellMotionFluedit.state())).areas.length, 1);
  const englishText = await page.locator('body').innerText();
  await page.locator('.site-language-toggle').click();
  await page.waitForFunction(() => document.documentElement.dataset.siteLanguage === 'zh');
  const chineseText = await page.locator('body').innerText();
  assert.ok(englishText.includes('Color intensity'));
  assert.ok(chineseText.includes('色彩强度'));
  assert.ok(!chineseText.includes('Color intensity'));
  await page.locator('#restoreScheme').click();
  await page.locator('#clearScheme').click();
  assert.equal((await page.evaluate(() => CellMotionFluedit.state())).stops.length, 2);
  await page.locator('#undo').click();
  assert.equal((await page.evaluate(() => CellMotionFluedit.state())).stops.length, 5);
  await page.locator('#restoreScheme').click();
  await page.waitForFunction(() => !document.documentElement.classList.contains('cm-language-fading'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/fluedit-cellmotion-mobile.png`, fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 320, height: 740 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1024, height: 768 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1440, height: 960 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight));
  await page.locator('.site-theme-toggle').click();
  await page.waitForFunction(() => !document.documentElement.classList.contains('site-theme-transition'));
  await page.screenshot({ path: `${output}/fluedit-cellmotion-dark.png` });
  await page.goto(`${base}/cellmotion-components.html`, { waitUntil: 'domcontentloaded' });
  const catalogLink = page.locator('#catalog-grid .card-caption a[href*="fluedit"]');
  await catalogLink.first().waitFor();
  await catalogLink.first().click(); await ready();
  assert.equal((await page.evaluate(() => CellMotionFluedit.state())).shape, 'butterfly');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ exports: ['PNG', 'GIF', 'MP4'], responsiveWidths: [320, 390, 1024, 1440], errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
