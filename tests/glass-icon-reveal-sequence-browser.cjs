// node tests/glass-icon-reveal-sequence-browser.cjs <node_modules directory> <browser executable> [base URL]
const path = require('node:path');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const { chromium } = require(path.resolve(process.argv[2] || 'node_modules', 'playwright'));
const base = (process.argv[4] || 'http://127.0.0.1:8767').replace(/\/$/, '');
const output = path.resolve(__dirname, '../output/glass-icon-reveal');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.argv[3] || undefined });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  try {
    await page.goto(`${base}/glass-icon-reveal.html`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => CellMotionGlassReveal.ready && !!CellMotionEffectBridge.getScheme, null, { timeout: 60000 });
    assert.equal(await page.locator('.tc-ai-trigger').count(), 1);
    await page.locator('#toggleTextScene').click();
    await page.locator('#sequenceText').fill('品牌 2026');
    await page.locator('#sequenceFont').selectOption('stg:noto-sc');
    await page.locator('#sequenceScale').evaluate(input => { input.value = '1.05'; input.dispatchEvent(new Event('input', { bubbles: true })); });
    await page.locator('#sequenceColor').fill('#bf2048');
    await page.waitForFunction(() => CellMotionGlassReveal.ready);
    assert.equal(await page.locator('#timeline .me-choreo-block').count(), 7);
    assert.equal(await page.evaluate(() => CellMotionGlassReveal.state().textScene.text), '品牌 2026');
    const frames = await page.evaluate(() => {
      const end = GlassRevealCore.endOf(CellMotionGlassReveal.state().P);
      CellMotionGlassReveal.seek(.84);
      const logo = document.querySelector('#view').toDataURL();
      CellMotionGlassReveal.seek(end + .84);
      const text = document.querySelector('#view').toDataURL();
      return { end, logo, text, duration: Number(document.querySelector('#scrubber').max) };
    });
    assert.notEqual(frames.logo, frames.text);
    assert.ok(frames.duration > frames.end * 2);
    await page.locator('#stageFrame').screenshot({ path: path.join(output, 'sequence-text.png') });
    await page.screenshot({ path: path.join(output, 'sequence-desktop.png') });
    await page.evaluate(end => CellMotionGlassReveal.seek(end + 1.45), frames.end);
    await page.locator('#stageFrame').screenshot({ path: path.join(output, 'sequence-text-final.png') });
    await page.locator('#headerBackground').fill('#dcecf7');
    assert.equal(await page.evaluate(() => CellMotionGlassReveal.state().P.background), '#dcecf7');
    await page.locator('#openCanvasSize').click();
    await page.locator('.glass-size-menu [data-size="1920x1080"]').click();
    assert.deepEqual(await page.evaluate(() => [CellMotionGlassReveal.state().width, CellMotionGlassReveal.state().height]), [1920, 1080]);
    const manifest = await page.evaluate(async () => {
      const definition = await (await fetch('effects/glass-icon-reveal.component.json')).json();
      const value = CellMotionAI.createManifest({ definition, scheme: CellMotionEffectBridge.getScheme(), baseUrl: document.baseURI });
      const check = CellMotionAI.validate(value);
      if (!check.valid) throw new Error(check.errors.join('; '));
      return value;
    });
    assert.equal(manifest.composition.scene.textScene.text, '品牌 2026');
    assert.equal(manifest.composition.canvas.width, 1920);
    assert.ok(manifest.assets.fonts.some(font => font.id === 'stg:noto-sc'));
    await page.locator('.tc-ai-trigger').click();
    const [popup] = await Promise.all([page.waitForEvent('popup'), page.locator('[data-ai-action="preview"]').click()]);
    await popup.waitForFunction(() => document.querySelector('#demoPlayer')?.iframe?.contentWindow?.CellMotionGlassReveal?.state().textScene.text === '品牌 2026', null, { timeout: 60000 });
    await popup.close();
    await page.locator('.tc-ai-trigger').click();
    const [componentDownload] = await Promise.all([page.waitForEvent('download'), page.locator('[data-ai-action="json"]').click()]);
    const componentPath = path.join(output, 'sequence-component.json'); await componentDownload.saveAs(componentPath);
    assert.equal(JSON.parse(fs.readFileSync(componentPath, 'utf8')).composition.scene.textScene.text, '品牌 2026');
    await page.locator('.tc-ai-trigger').click();
    await page.locator('[data-ai-action="params"]').click();
    assert.ok((await page.locator('.tc-ai-dialog').textContent()).includes('composition.scene.textScene.scale'));
    await page.locator('.tc-ai-dialog [data-ai-close]').click();
    const [projectDownload] = await Promise.all([page.waitForEvent('download'), page.locator('#saveScheme').click()]);
    const projectPath = path.join(output, 'sequence-project.json'); await projectDownload.saveAs(projectPath);
    await page.locator('#restoreScheme').click();
    assert.equal(await page.evaluate(() => CellMotionGlassReveal.state().textScene.enabled), false);
    await page.locator('#schemeFile').setInputFiles(projectPath);
    await page.waitForFunction(() => CellMotionGlassReveal.state().textScene.text === '品牌 2026' && CellMotionGlassReveal.state().textScene.enabled);
    const demo = await context.newPage();
    demo.on('pageerror', error => errors.push(error.message));
    await demo.goto(`${base}/typecascade-component-demo.html?effect=glass-icon-reveal`, { waitUntil: 'domcontentloaded' });
    await demo.waitForFunction(() => document.querySelector('#demoPlayer')?.duration > 0, null, { timeout: 60000 });
    await demo.evaluate(value => { document.querySelector('#demoPlayer').manifest = value; }, manifest);
    await demo.waitForFunction(() => {
      const player = document.querySelector('#demoPlayer');
      return Math.abs(player.duration - 4.7) < .3 && player.iframe.contentWindow?.CellMotionGlassReveal?.state().textScene.text === '品牌 2026';
    }, null, { timeout: 60000 });
    await demo.evaluate(() => { const player = document.querySelector('#demoPlayer'); player.pause(); player.seek(2.8); });
    await demo.waitForFunction(() => Math.abs(document.querySelector('#demoPlayer').iframe.contentWindow.CellMotionGlassReveal.time - 2.8) < .01);
    await demo.evaluate(() => document.querySelector('#demoPlayer').restart());
    await demo.waitForFunction(() => document.querySelector('#demoPlayer').iframe.contentWindow.CellMotionGlassReveal.time < .6);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForTimeout(150);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.evaluate(() => CellMotionGlassReveal.seek(GlassRevealCore.endOf(CellMotionGlassReveal.state().P) + .84));
    await page.screenshot({ path: path.join(output, 'sequence-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.locator('#canvasPreset').selectOption('custom');
    await page.locator('#canvasWidth').fill('256'); await page.locator('#canvasWidth').dispatchEvent('change');
    await page.locator('#canvasHeight').fill('256'); await page.locator('#canvasHeight').dispatchEvent('change');
    await page.locator('#openExport').click();
    await page.locator('#exportScale').selectOption('0.25');
    await page.locator('#exportFps').selectOption('15');
    const [download] = await Promise.all([page.waitForEvent('download', { timeout: 180000 }), page.locator('#exportMp4').click()]);
    const filename = path.join(output, 'sequence-64x64.mp4');
    await download.saveAs(filename);
    assert.ok(fs.statSync(filename).size > 1000);
    const svg = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><circle cx="32" cy="32" r="24" fill="#da2f55"/></svg>');
    await page.locator('#logoFile').setInputFiles({ name: 'brand.svg', mimeType: 'image/svg+xml', buffer: svg });
    await page.waitForFunction(() => CellMotionGlassReveal.ready && CellMotionGlassReveal.state().assetUrl.startsWith('data:image/svg+xml'));
    const mediaManifest = await page.evaluate(async () => CellMotionAI.createManifest({ definition: await (await fetch('effects/glass-icon-reveal.component.json')).json(), scheme: CellMotionEffectBridge.getScheme(), baseUrl: document.baseURI }));
    assert.ok(mediaManifest.assets.embedded.some(asset => asset.source === 'composition.scene.assetUrl'));
    await demo.evaluate(value => { document.querySelector('#demoPlayer').manifest = value; }, mediaManifest);
    await demo.waitForFunction(() => document.querySelector('#demoPlayer')?.iframe?.contentWindow?.CellMotionGlassReveal?.state().assetUrl.startsWith('data:image/svg+xml'));
    assert.deepEqual(errors, []);
    console.log('Logo → text sequence, header controls, live AI player and MP4: PASS');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
